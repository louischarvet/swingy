package swingy.model;

public class HeroSchema {
	private String	name;
	private String	klass;

	public void	setName(String name) {
		this.name = name;
	}

	public void	setKlass(String klass) {
		this.klass = klass;
	}

	public String	getName() {
		return name;
	}

	public String	getKlass() {
		return klass;
	}
}